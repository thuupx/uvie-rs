/// Compare a `[char]` slice against a `&str`, case-insensitively.
/// Returns `Equal` if they match (ignoring case), `Less`/`Greater` otherwise.
#[inline]
fn compare_chars_to_str(chars: &[char], s: &str) -> Ordering {
    let mut si = s.chars();
    for &c in chars {
        match si.next() {
            Some(sc) => {
                let cl = c.to_ascii_lowercase();
                let scl = sc.to_ascii_lowercase();
                match cl.cmp(&scl) {
                    Ordering::Equal => continue,
                    ord => return ord,
                }
            }
            None => return Ordering::Greater,
        }
    }
    if si.next().is_some() {
        Ordering::Less
    } else {
        Ordering::Equal
    }
}

/// Returns `true` if `word` (as a char slice) matches a known English word
/// that should pass through verbatim instead of being transformed.
///
/// Case-insensitive. Uses binary search on a sorted static array.
/// Only called at word boundaries (space/commit), never per-keystroke.
#[inline]
pub fn is_english_override(word: &[char]) -> bool {
    if word.is_empty() || word.len() < 4 {
        return false;
    }
    let mut lo = 0usize;
    let mut hi = ENGLISH_OVERRIDES.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_chars_to_str(word, ENGLISH_OVERRIDES[mid]) {
            Ordering::Equal => return true,
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lookup() {
        assert!(is_english_override(&[
            'c', 'h', 'a', 'r', 'a', 'c', 't', 'e', 'r'
        ]));
        assert!(is_english_override(&['s', 'a', 'f', 'a', 'r', 'i']));
        assert!(is_english_override(&['S', 'A', 'F', 'A', 'R', 'I'])); // case-insensitive
        assert!(is_english_override(&['e', 'f', 'f', 'e', 'c', 't']));
        assert!(is_english_override(&['g', 'o', 'o', 'd'])); // garbled (gôd not Vietnamese)
        assert!(is_english_override(&['b', 'o', 'o', 'k'])); // garbled (bôk not Vietnamese)
        assert!(!is_english_override(&['c', 'h', 'a', 'o', 's'])); // excluded (cháo is Vietnamese)
        assert!(!is_english_override(&['m', 'o', 's', 't'])); // excluded (mót is Vietnamese)
        assert!(!is_english_override(&['u', 's', 'e', 'r'])); // excluded (u+sẻ V-C-V split)
        assert!(!is_english_override(&['h', 'e', 'l', 'l', 'o'])); // not in list
        assert!(!is_english_override(&['a', 's'])); // too short
        assert!(!is_english_override(&[]));
    }
}
